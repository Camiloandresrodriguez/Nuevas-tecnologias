#Nota. todo lo que se ingrese en un input se tomara como un string, 
#por lo que si se desea ingresar un numero se debe convertir a int o float segun sea el caso.
nombre = input("Ingrese su nombre: ")
print(f"el nombre registrado es: {nombre}")

#convertir input a int
edad = int(input("Ingrese su edad: "))
print(f"la edad registrada es: {edad}")

#convertir input a float
altura = float(input("Ingrese su altura: "))
print(f"la altura registrada es: {altura}")

